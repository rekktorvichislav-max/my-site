export type Dict = typeof ru;

export const dicts: Record<Lang, Dict> = { ru, en };

export function getDict(lang: Lang): Dict {
  return dicts[lang];
}

export function detectLang(cookieValue: string | undefined): Lang {
  return cookieValue === "en" ? "en" : "ru";
}

export function translate(dict: Dict, key: string, vars?: Record<string, string>): string {
  const raw = dict[key as keyof Dict];
  const template = typeof raw === "string" ? raw : key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? `{${name}}`);
}
